#!/usr/bin/env node
// Story 2.4 — generate app/src/parts/svgRegistry.js (+ .d.ts) from QA-passed traces.
//
// Reads tools/art-lab/out/trace-svg-report.json (written by trace-svg.mjs) and
// emits a static Metro-safe string-module registry: inner <g> markup per part in
// the 1024x1536 space, keyed by the exact catalog id. Only parts with pass:true
// enter — the report IS the QA gate ("file presence means nothing").
//
// Emitted as plain .js + .d.ts (not .ts) so the SAME module serves Metro (bundled
// string module), tsc (via the .d.ts), and Node gate scripts (engine-smoke twin
// imports it directly — no .runtime.js mirror to keep in sync).
//
// The generated file is committed: unlike the gitignored PNG assets, the SVG
// premium path is self-contained in source, so a fresh clone renders it.

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const REPORT = join(ROOT, "tools/art-lab/out/trace-svg-report.json");
const OPT_DIR = join(ROOT, "tools/art-lab/out/svg-opt");
const OUT = join(ROOT, "app/src/parts/svgRegistry.js");
const OUT_DTS = join(ROOT, "app/src/parts/svgRegistry.d.ts");

const report = JSON.parse(readFileSync(REPORT, "utf8"));
const keys = Object.keys(report.parts).filter((k) => report.parts[k].pass).sort();

const entries = [];
const bboxEntries = [];
for (const key of keys) {
  const [cat, id] = key.split("/");
  const svg = readFileSync(join(OPT_DIR, cat, `${id}.svg`), "utf8");
  const m = svg.match(/^<svg[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!m) throw new Error(`${key}: cannot extract inner markup`);
  let inner = m[1].trim();
  // one enclosing <g> per part so the compositor can prefix tint/transform cleanly
  if (!(inner.startsWith("<g") && inner.endsWith("</g>") && inner.indexOf("<g", 2) === -1)) {
    inner = `<g>${inner}</g>`;
  }
  if (inner.includes("`") || inner.includes("${")) {
    throw new Error(`${key}: markup would break the template literal`);
  }
  entries.push(`  "${key}": \`${inner}\`,`);
  const bbox = report.parts[key].bbox;
  if (bbox) bboxEntries.push(`  "${key}": [${bbox.join(", ")}],`);
}

const total = entries.reduce((s, e) => s + Buffer.byteLength(e), 0);
const banner = `// GENERATED by tools/art-gen/gen-svg-registry.mjs — DO NOT EDIT.
// Regenerate: node tools/art-gen/trace-svg.mjs && node tools/art-gen/gen-svg-registry.mjs
//
// SVG parts registry — vector twin of registry.ts (Story 2.4). Each value is the
// part's inner <g> markup in the canonical 1024x1536 full-frame space (registration
// baked in — composites 1:1 with zero per-part offset). Keys are exact catalog ids.
// Only trace-QA-passed parts enter (${keys.length} parts, ${(total / 1024).toFixed(0)} KB on ${report.date}).
// Tint at composite time = per-fill multiply (SvgPartsFigure); parts stay neutral here.
// Plain .js + .d.ts so Metro, tsc, and Node gate scripts all read the same module.
`;

const header = `${banner}
/* eslint-disable */
export const PARTS_SVG = {
`;

const footer = `};

// Trace-time ink bounds [x0, y0, x1, y1] in the canonical 1024x1536 frame —
// lets the compositor drop layers that cannot intersect a crop viewBox.
export const PARTS_SVG_BBOX = {
${bboxEntries.join("\n")}
};

export const hasSvgPart = (key) =>
  Object.prototype.hasOwnProperty.call(PARTS_SVG, key);

export const svgPartRef = (key) => PARTS_SVG[key];

export const svgPartCount = () => Object.keys(PARTS_SVG).length;
`;

const dts = `${banner}
export declare const PARTS_SVG: Record<string, string>;
export declare const PARTS_SVG_BBOX: Record<string, readonly number[]>;
export declare const hasSvgPart: (key: string) => boolean;
export declare const svgPartRef: (key: string) => string | undefined;
export declare const svgPartCount: () => number;
`;

writeFileSync(OUT, header + entries.join("\n") + "\n" + footer);
writeFileSync(OUT_DTS, dts);
console.log(`wrote ${OUT} (+.d.ts): ${keys.length} parts, ${(total / 1048576).toFixed(2)} MB markup`);
